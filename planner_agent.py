import json
from ollama import Client

## System prompt for the Planner Agent
## Describe its role, the expected output format, and the rules it must follow when generating a navigation plan.
## These are fairly similar to the Analyst Agent, but with a focus on creating a plan based on the requirements provided by the Analyst Agent.
PLANNER_SYSTEM_PROMPT = """
You are a professional Navigation Planner Agent.
Your task: Based on the validated software requirements, design a detailed robot navigation plan and output it strictly in valid JSON format.

Rules you must follow:
1. Output ONLY the JSON object, no extra explanation, no markdown code blocks, no comments, no prefix/suffix text.
2. The robot can only perform these actions: FORWARD, LEFT, RIGHT, STOP. No other actions allowed.
3. The plan must describe a strategy for robot navigation.
4. The plan must list concrete decisions the robot can take during navigation.
5. The plan must specify the conditions under which the robot must stop.

Output JSON structure must be exactly:
{
    "strategy": "a string describing the overall navigation strategy",
    "decisions": [
        {"condition": "string describing the situation", "action": "FORWARD or LEFT or RIGHT or STOP"}
    ],
    "stop_conditions": [
        "string describing a condition that triggers a stop"
    ]
}

Make sure the decisions cover all sensor scenarios:
- Goal is ahead and path ahead is clear
- Goal is ahead but path ahead is blocked
- Goal is to the left and path left is clear
- Goal is to the left but path left is blocked
- Goal is to the right and path right is clear
- Goal is to the right but path right is blocked
- No safe direction available
"""

## Function to validate the plan generated by the Planner Agent
## It should first check that the parameter it receives is of the correct type. 
# Then, it should validate all the keys and values contained in the above Python data structure of the input parameter.
def validate_plan(data):
    if not isinstance(data, dict):
        return False

    required_keys = {"strategy", "decisions", "stop_conditions"}
    if set(data.keys()) != required_keys:
        return False


    if not isinstance(data["strategy"], str) or len(data["strategy"].strip()) == 0:
        return False

    if not isinstance(data["decisions"], list) or len(data["decisions"]) == 0:
        return False

    valid_actions = {"FORWARD", "LEFT", "RIGHT", "STOP"}
    for decision in data["decisions"]:
        if not isinstance(decision, dict):
            return False
        if set(decision.keys()) != {"condition", "action"}:
            return False
        if not isinstance(decision["condition"], str) or len(decision["condition"].strip()) == 0:
            return False
        if decision["action"] not in valid_actions:
            return False

    if not isinstance(data["stop_conditions"], list) or len(data["stop_conditions"]) == 0:
        return False
    for cond in data["stop_conditions"]:
        if not isinstance(cond, str) or len(cond.strip()) == 0:
            return False

    return True


## Function to run the Planner Agent
## It takes the requirements generated by the Analyst Agent as input, sends them to the Planner Agent. Just like you did with the Analyst Agent.
## Take the response from the Planner Agent (Qwen), parse it and validate it using the validate_plan function, and return the validated plan.
def run_planner(requirement):
    client = Client(host="http://127.0.0.1:11434")

    user_content = json.dumps(requirement, indent=2)

    response = client.chat(
        model="qwen3:8b",
        messages=[
            {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
            {"role": "user", "content": f"Here are the validated requirements:\n{user_content}\n\nGenerate the navigation plan."}
        ]
    )

    json_text = response["message"]["content"]

    json_text = json_text.strip()
    if json_text.startswith("```json"):
        json_text = json_text[7:]
    if json_text.startswith("```"):
        json_text = json_text[3:]
    if json_text.endswith("```"):
        json_text = json_text[:-3]
    json_text = json_text.strip()

    try:
        plan = json.loads(json_text)
    except json.JSONDecodeError:
        raise ValueError("Qwen output is not valid JSON, please optimize the prompt.")

    if not validate_plan(plan):
        raise ValueError("Validation failed: plan structure or type is incorrect.")

    return plan
